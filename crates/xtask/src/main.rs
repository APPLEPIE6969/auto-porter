//! xtask — generates `docs/feature-mapping.md` from `native-hooks.json` plus
//! the hand-maintained Java-side column (spec §1, §3.1).
//!
//! `cargo run -p xtask -- feature-mapping [--hooks-json PATH] [--out PATH]`
//!
//! The gate: if a hook name referenced by the mapping table is missing from
//! the catalog, this command exits non-zero — CI treats that as a build
//! failure, so a mapping can never silently reference a nonexistent hook.

use shared::catalog::HookCatalog;
use std::path::{Path, PathBuf};

fn main() {
    let mut args: Vec<String> = std::env::args().skip(1).collect();
    // subcommand form: `xtask feature-mapping [flags]`
    if args
        .first()
        .map(|a| a == "feature-mapping")
        .unwrap_or(false)
    {
        args.remove(0);
    }
    let mut hooks_json: Option<PathBuf> = None;
    let mut out = PathBuf::from("docs/feature-mapping.md");
    let mut it = args.into_iter();
    while let Some(arg) = it.next() {
        match arg.as_str() {
            "--hooks-json" => hooks_json = it.next().map(PathBuf::from),
            "--out" => out = it.next().map(PathBuf::from).unwrap_or(out),
            other => {
                eprintln!("unknown xtask argument: {other}");
                eprintln!("usage: xtask feature-mapping [--hooks-json PATH] [--out PATH]");
                std::process::exit(2);
            }
        }
    }

    let catalog = match HookCatalog::load_or_snapshot(hooks_json.as_deref()) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("error: {e}");
            std::process::exit(1);
        }
    };

    match generate(&catalog, &out) {
        Ok(()) => println!(
            "wrote {} ({} hooks in catalog)",
            out.display(),
            catalog.hooks.len()
        ),
        Err(errors) => {
            eprintln!("error: the mapping table references hooks missing from the catalog:");
            for e in &errors {
                eprintln!("  - {e}");
            }
            std::process::exit(1);
        }
    }
}

fn generate(catalog: &HookCatalog, out: &Path) -> Result<(), Vec<String>> {
    let mut errors = Vec::new();

    // Resolve every hook referenced by the mapping rules up front: one missing
    // name fails the whole generation.
    let mut resolved_event_rows: Vec<(String, String, String, String)> = Vec::new();
    for rule in classify::rules::RULES {
        match catalog.resolve(rule.hook) {
            Ok(def) => {
                resolved_event_rows.push((
                    rule.concept.to_string(),
                    def.name.clone(),
                    def.contract.clone(),
                    rule.tier.as_str().to_string(),
                ));
            }
            Err(e) => errors.push(e),
        }
    }
    let mut resolved_struct_rows: Vec<(String, String, String, String)> = Vec::new();
    for rule in classify::rules::STRUCTURAL {
        match catalog.resolve(rule.hook) {
            Ok(def) => {
                resolved_struct_rows.push((
                    rule.concept.to_string(),
                    def.name.clone(),
                    def.contract.clone(),
                    rule.tier.as_str().to_string(),
                ));
            }
            Err(e) => errors.push(e),
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }

    let mut md = String::new();
    md.push_str("# Feature mapping (Java concept → Horizon hook)\n\n");
    md.push_str("> Generated by `cargo run -p xtask -- feature-mapping` from the hook catalog");
    if let Some(src) = &catalog.source {
        md.push_str(&format!(" — {}", src.trim_end_matches('.')));
    }
    md.push_str(
        ". Do not edit by hand: the Horizon column is a lookup against \
         `native-hooks.json` at the pinned revision, and `xtask` fails the build \
         when a referenced name is missing.\n\n",
    );
    md.push_str(&format!(
        "NATIVE_HOOKS_API at this catalog: **{}** · hooks defined: **{}**\n\n",
        catalog.native_hooks_api,
        catalog.hooks.len()
    ));

    md.push_str("## Event mappings\n\n");
    md.push_str("| Java concept | Horizon hook (resolve in native-hooks.json) | Contract | Tier |\n|---|---|---|---|\n");
    for (concept, hook, contract, tier) in &resolved_event_rows {
        md.push_str(&format!(
            "| {} | `{hook}` | {contract} | {tier} |\n",
            concept.replace('|', "\\|")
        ));
    }

    md.push_str("\n## Structural mappings\n\n");
    md.push_str("| Java structure | Horizon hook | Contract | Tier |\n|---|---|---|---|\n");
    for (concept, hook, contract, tier) in &resolved_struct_rows {
        md.push_str(&format!(
            "| {} | `{hook}` | {contract} | {tier} |\n",
            concept.replace('|', "\\|")
        ));
    }

    md.push_str("\n## Tier definitions\n\n");
    md.push_str("| Tier | Description | Automation |\n|---|---|---|\n");
    md.push_str("| A | Pure content | Fully automatic (horizon-port-pack) |\n");
    md.push_str("| B | Simple behaviour | Mostly automatic, human review |\n");
    md.push_str("| C | Complex behaviour | Partly automatic, human design |\n");
    md.push_str("| D | No hook / overhaul | Report only |\n\n");
    md.push_str("A hook whose name is missing from the pinned catalog demotes its feature to **Tier D** with a GapReport entry (spec §3.1).\n");

    if let Some(parent) = out.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    std::fs::write(out, md).map_err(|e| vec![format!("cannot write {}: {e}", out.display())])
}
